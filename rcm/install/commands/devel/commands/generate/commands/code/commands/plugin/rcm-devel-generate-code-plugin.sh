#!/bin/bash

[ -f "$0" ] || { echo "Cannot run as dot command." >&2; kill -INT $$; }

# Define variables and constants.
RCM_EXTENSION_VERSION=0.1.0-alpha.1

# Usage Functions.
usage() {
    cat << EOF
Usage: rcm devel generate code plugin [options]

Generate shell command to make shell script of command.

Options:
   --interface=INTERFACE
        Set the name of interface.
   --plugin-name=NAME
        Set the name of plugin.
   --method=[METHOD]
        Set the name of method.

Global Options:
   --version
        Print version of this script.
   --help
        Show this help.

EOF
}

# Prevent scripts from being executed directly.
[ -f "${RCM_LIB}/require.sh" ] && source "${RCM_LIB}/require.sh" || { usage >&2; exit 1; }

# Parse arguments. Generated by parse-options.sh.
_new_arguments=()
while [[ $# -gt 0 ]]; do
    case "$1" in
        --help) help=1; shift ;;
        --version) version=1; shift ;;
        --interface=*) interface="${1#*=}"; shift ;;
        --interface) if [[ ! $2 == "" && ! $2 =~ (^--$|^-[^-]|^--[^-]) ]]; then interface="$2"; shift; fi; shift ;;
        --method=*) method="${1#*=}"; shift ;;
        --method) if [[ ! $2 == "" && ! $2 =~ (^--$|^-[^-]|^--[^-]) ]]; then method="$2"; shift; fi; shift ;;
        --plugin-name=*) plugin_name="${1#*=}"; shift ;;
        --plugin-name) if [[ ! $2 == "" && ! $2 =~ (^--$|^-[^-]|^--[^-]) ]]; then plugin_name="$2"; shift; fi; shift ;;
        --[^-]*) shift ;;
        *) _new_arguments+=("$1"); shift ;;
    esac
done
set -- "${_new_arguments[@]}"
unset _new_arguments

# Help and Version.
[ -n "$help" ] && { usage; exit 0; }
[ -n "$version" ] && { e $RCM_EXTENSION_VERSION; x; }

# ------------------------------------------------------------------------------

# Title.
title rcm devel generate code plugin
____

# Mapping operand to value of options.

chapter Mapping operand as value of options.
if [ -n "$1" ];then
    code --interface=$1
    interface=$1; shift
fi
if [ -n "$1" ];then
    code --plugin-name=$1
    plugin_name=$1; shift
fi
if [ -n "$1" ];then
    code --method=$1
    method=$1; shift
fi
____

# Require, validate, and populate value.
chapter Variable dump.
if [ -z "$interface" ];then
    error "Argument --interface required."; x
fi
code 'interface="'$interface'"'
if [ -z "$plugin_name" ];then
    error "Argument --plugin-name required."; x
fi
code 'plugin_name="'$plugin_name'"'
code 'method="'$method'"'
code 'RCM_LIB="'"$RCM_LIB"'"'
RCM_PREFIX="$RCM_LIB"

# Jika current directory terdapat direktori rcm/install, maka diasumsikan kita
# berada di repository extension nya rcm.
# Contoh: $PWD = /home/ijortengab/github.com/ijortengab/ispconfig-autoinstaller
# Terdapat direktori
# /home/ijortengab/github.com/ijortengab/ispconfig-autoinstaller/rcm/install
# maka variable RCM_PREFIX akan bernilai "$PWD/rcm/install".
git_repo=
if [ -d "$PWD/rcm/install" ];then
    RCM_REPOSITORY="$PWD/rcm/install"
    RCM_PREFIX="$PWD/rcm/install"
    git_repo=1
elif [ -d "$PWD/install/interfaces" ];then
    # Ini artinya kita berada di repository rcm.
    RCM_REPOSITORY="$PWD/install"
    RCM_PREFIX="$PWD/install"
    git_repo=1
fi
code 'RCM_REPOSITORY="'"$RCM_REPOSITORY"'"'
code 'RCM_PREFIX="'"$RCM_PREFIX"'"'
____

code cd '      ' "$RCM_PREFIX"
echo cd '      ' "$RCM_PREFIX"

RCM_PREFIX=
script_alias=
RCM_PREFIX+="interfaces/${interface}"
# Jika mengandung slash, maka berarti perlu direktori.
if [[ "$interface" =~ / ]];then
    dirname=$(dirname "$interface")
    basename=$(basename "$interface")
else
    dirname=
    basename="$interface"
fi
script_alias+="$basename"
RCM_PREFIX+="/implements/$plugin_name"
script_alias+=."$plugin_name"
if [ -z "$method" ];then
    code mkdir -p '' "$RCM_PREFIX"
    echo mkdir -p '' "$RCM_PREFIX"
else
    RCM_PREFIX+="/methods/$method"
    script_alias+=."$method"
    script_alias+=".sock"
    script_alias="${script_alias/\//-}"
    code mkdir -p '' "$RCM_PREFIX"
    echo mkdir -p '' "$RCM_PREFIX"
    code touch '   ' "$RCM_PREFIX/socket.sh"
    echo touch '   ' "$RCM_PREFIX/socket.sh"
    code chmod a-x "$RCM_PREFIX/socket.sh"
    echo chmod a-x "$RCM_PREFIX/socket.sh"
    back=..
    if [ -n "$dirname" ];then
        IFS=/ read -ra array <<< "$dirname"
        for each in "${array[@]}";do
            back+=/..
        done
        dirname="/${dirname}"
    fi

    code mkdir -p '' "$RCM_LIB/shortcut-plugin${dirname}";
    echo mkdir -p '' "$RCM_LIB/shortcut-plugin${dirname}";
    code cd '      ' "$RCM_LIB/shortcut-plugin${dirname}"
    echo cd '      ' "$RCM_LIB/shortcut-plugin${dirname}"
    if [ -n "$git_repo" ];then
        code ln -sf '  ' ${RCM_REPOSITORY}/${RCM_PREFIX}/socket.sh ${script_alias}
        echo ln -sf '  ' ${RCM_REPOSITORY}/${RCM_PREFIX}/socket.sh ${script_alias}
    else
        code ln -sf '  ' ${back}/${RCM_PREFIX#${RCM_LIB}}/socket.sh ${script_alias}
        echo ln -sf '  ' ${back}/${RCM_PREFIX#${RCM_LIB}}/socket.sh ${script_alias}
    fi

fi

# Wajib exit 0 jika success.
exit 0

